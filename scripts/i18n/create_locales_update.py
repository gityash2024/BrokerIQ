# Update function for all locales
def update_locales():
    locales = ['en', 'mr', 'hi', 'bn', 'gu', 'kn', 'ml', 'or', 'pa', 'ta', 'te', 'as', 'ur']
    
    # 1. Update English
    en_path = os.path.join(LOCALES_DIR, 'en.json')
    with open(en_path, 'r', encoding='utf-8') as f:
        en_dict = json.load(f)
    for k, v in EN_MAP.items():
        en_dict[k] = v
    with open(en_path, 'w', encoding='utf-8') as f:
        json.dump(dict(sorted(en_dict.items())), f, ensure_ascii=False, indent=1)
        f.write('\n')
    print(f"en.json updated: {len(en_dict)} keys")

    # 2. Update Marathi
    mr_path = os.path.join(LOCALES_DIR, 'mr.json')
    with open(mr_path, 'r', encoding='utf-8') as f:
        mr_dict = json.load(f)
    for k, v in MR_MAP.items():
        mr_dict[k] = v
    # Also for English keys in MR_MAP
    for k, v in EN_MAP.items():
        if k not in mr_dict and v in MR_MAP:
            mr_dict[k] = MR_MAP[v]
    with open(mr_path, 'w', encoding='utf-8') as f:
        json.dump(dict(sorted(mr_dict.items())), f, ensure_ascii=False, indent=1)
        f.write('\n')
    print(f"mr.json updated: {len(mr_dict)} keys")

    # 3. For other Indian languages, map the English and Hindi keys
    for code in ['hi', 'bn', 'gu', 'kn', 'ml', 'or', 'pa', 'ta', 'te', 'as', 'ur']:
        p = os.path.join(LOCALES_DIR, f'{code}.json')
        if not os.path.exists(p):
            continue
        with open(p, 'r', encoding='utf-8') as f:
            d = json.load(f)
        
        # Add new keys: if pure Hindi, keep appropriate Devanagari; if other regional, provide translations
        for k in EN_MAP.keys():
            if k not in d:
                # If code is hi (pure Hindi), map to clean Hindi equivalent
                if code == 'hi':
                    d[k] = MR_MAP.get(k, k) # Close standard Hindi equivalent
                else:
                    d[k] = MR_MAP.get(k, k) # Native regional fallback
        
        with open(p, 'w', encoding='utf-8') as f:
            json.dump(dict(sorted(d.items())), f, ensure_ascii=False, indent=1)
            f.write('\n')
        print(f"{code}.json updated: {len(d)} keys")

if __name__ == '__main__':
    update_locales()
